using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace PCL.Core.SourceGenerators;

[Generator(LanguageNames.CSharp)]
public class EnvironmentInteropGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var serviceTemplate = context.AdditionalTextsProvider
            .Where(file => Path.GetFileName(file.Path) == ".env.example");
        var secretProvider = serviceTemplate.Select(static (file, token) =>
        {
            // 只有发布构建显式传入 PCL_WRITE_SECRET=1 时才允许把环境变量写入产物。
            // 空的 PCL_WRITE_SECRET（例如 CI 中条件注入产生空字符串）不能触发。
#pragma warning disable RS1035
            var writeSecret = Environment.GetEnvironmentVariable("PCL_WRITE_SECRET");
            if (writeSecret != "1" || file.GetText(token) is not { } template)
                return Array.Empty<(string, string)>();
            return (from line in template.Lines
                    let key = line.ToString().Split('=')[0].Trim()
                    where key.StartsWith("PCL_", StringComparison.Ordinal)
                    let value = Environment.GetEnvironmentVariable(key)
                    where !string.IsNullOrWhiteSpace(value)
                    select (key.Substring(4), value!)).ToArray();
#pragma warning restore RS1035
        });

        // 注册源代码输出
        context.RegisterSourceOutput(
            secretProvider,
            static (spc, secretPairs) => _Execute(spc, secretPairs));
    }

    private static void _Execute(
        SourceProductionContext context,
        IEnumerable<(string, string)> secretPairs)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated />");
        sb.AppendLine("// 此文件由 Source Generator 自动生成，请勿手动修改");
        sb.AppendLine();
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("namespace PCL.Core.Utils.OS;");
        sb.AppendLine();
        sb.AppendLine("partial class EnvironmentInterop");
        sb.AppendLine("{");
        sb.AppendLine(
            "    private static readonly System.Collections.Generic.Dictionary<string, string?> SecretDictionary = new()");
        sb.AppendLine("    {");

        foreach (var (key, value) in secretPairs)
            sb.AppendLine($"        [\"{key}\"] = {_ToVerbatimString(value)},");

        sb.AppendLine("    };");
        sb.AppendLine("}");

        context.AddSource("EnvironmentInterop.g.cs", SourceText.From(sb.ToString(), Encoding.UTF8));
    }

    private static string _ToVerbatimString(string text)
    {
        return "@\"" + text.Replace("\"", "\"\"") + "\"";
    }
}
